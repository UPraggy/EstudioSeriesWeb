// GET /SaldoOpenRouter — só números de saldo/limite da chave (nunca a chave nem o label dela).
const servico = require('../openrouter/servico');
const { limparSegredos } = require('../openrouter/erros');

exports.REST = async (req, res) => {
    try {
        return res.json(await servico.saldo());
    } catch (error) {
        const msg = limparSegredos(error.message);
        console.error('Error:', msg);
        res.status(500).json({ Error: msg });
    }
};
